export function iconComponent(
    name: string | null | undefined,
): LucideIcon | null {
    if (name === null || name === undefined || !(name in iconComponents)) {
        return null;
    }

    return iconComponents[name as IconName];
}

export function iconLabel(name: string | null | undefined): string | null {
    if (name === null || name === undefined || !(name in iconLabels)) {
        return null;
    }

    return iconLabels[name as IconName];
}
